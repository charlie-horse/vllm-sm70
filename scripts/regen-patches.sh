#!/usr/bin/env bash
# Regenerate patches/ from the working branch of an upstream vLLM checkout.
#
#   scripts/regen-patches.sh <vllm-checkout> [base-tag] [branch]
#   scripts/regen-patches.sh --check <vllm-checkout> [base-tag]
#
# Defaults: base-tag = the tag in patches/BASE, branch = sm70.
# Regen mode writes patches/NNNN-<subject>.patch plus patches/series, and
# fails if any commit is missing a required header field.
# --check mode applies patches/series onto a fresh worktree of base-tag with
# `git am` (no 3-way merge, so stale context fails) and stops at the first
# patch that does not apply cleanly.
set -euo pipefail

repo_root=$(cd "$(dirname "$0")/.." && pwd)
patch_dir=$repo_root/patches
required_fields=(What Why Upstream-files Kill-switch Tests Upstream-status)

die() { echo "regen-patches: $*" >&2; exit 1; }

mode=regen
if [[ ${1:-} == --check ]]; then mode=check; shift; fi
src=${1:?usage: regen-patches.sh [--check] <vllm-checkout> [base-tag] [branch]}
base=${2:-$(cat "$patch_dir/BASE" 2>/dev/null || true)}
branch=${3:-sm70}
[[ -n $base ]] || die "no base tag given and patches/BASE is missing"
git -C "$src" rev-parse -q --verify "refs/tags/$base" >/dev/null \
  || die "tag $base not found in $src"

if [[ $mode == check ]]; then
  [[ -f $patch_dir/series ]] || die "patches/series missing"
  wt=$(mktemp -d)
  trap 'git -C "$src" worktree remove --force "$wt" >/dev/null 2>&1 || true' EXIT
  git -C "$src" worktree add -q --detach "$wt" "$base"
  while read -r p; do
    [[ -z $p || $p == \#* ]] && continue
    git -C "$wt" -c user.name=check -c user.email=check@localhost \
      am -q "$patch_dir/$p" || die "patch does not apply: $p"
    echo "ok  $p"
  done < "$patch_dir/series"
  echo "series applies cleanly on $base"
  exit 0
fi

git -C "$src" rev-parse -q --verify "$branch" >/dev/null || die "branch $branch not found"
git -C "$src" merge-base --is-ancestor "$base" "$branch" \
  || die "$branch is not based on $base (rebase first)"
[[ -z $(git -C "$src" status --porcelain) ]] || die "$src has uncommitted changes"

# Every commit must carry the header fields (see docs/patch-header.md).
bad=0
for c in $(git -C "$src" rev-list --reverse "$base..$branch"); do
  body=$(git -C "$src" log -1 --format=%B "$c")
  for f in "${required_fields[@]}"; do
    grep -q "^$f:" <<<"$body" || { echo "missing '$f:' in $(git -C "$src" log -1 --format='%h %s' "$c")" >&2; bad=1; }
  done
done
[[ $bad == 0 ]] || die "fix the commit messages above, then rerun"

# Stable output: no version signature, zeroed From line, fixed abbrev.
find "$patch_dir" -maxdepth 1 -name '[0-9][0-9][0-9][0-9]-*.patch' -delete
git -C "$src" format-patch -q --no-signature --zero-commit --abbrev=12 \
  --no-stat --no-numbered -o "$patch_dir" "$base..$branch"

echo "$base" > "$patch_dir/BASE"
{
  echo "# Generated by scripts/regen-patches.sh; applied in order onto $base"
  (cd "$patch_dir" && ls [0-9][0-9][0-9][0-9]-*.patch 2>/dev/null || true)
} > "$patch_dir/series"

n=$(grep -vc '^#' "$patch_dir/series" || true)
echo "wrote $n patches onto $base ($(git -C "$src" rev-parse --short=12 "$base^{commit}"))"
