def _llm(a, **extra):
    from vllm import LLM

    kw = dict(
        model=a.model, tensor_parallel_size=a.tp, dtype="half",
        max_model_len=8192, max_num_seqs=1, gpu_memory_utilization=a.gpu_util,
        enable_prefix_caching=False,
    )
    if a.hf_overrides:
        kw["hf_overrides"] = json.loads(a.hf_overrides)
    kw.update(extra)
    return LLM(**kw)


def _close(llm):
    import gc

    try:
        llm.llm_engine.engine_core.shutdown()
    except Exception:  # noqa: BLE001 - best effort; memory is checked by the caller
        pass
    del llm
    gc.collect()


def cmd_gen(a):
    from vllm import SamplingParams

    sets = a.set or [0]
    for k in sets:
        if k not in PROMPT_SETS:
            raise SystemExit(f"unknown prompt set {k}; have {sorted(PROMPT_SETS)}")
    if a.out and len(sets) != 1:
        raise SystemExit("--out takes one --set; use --out-dir for several")
    llm = _llm(a, enforce_eager=True)
    try:
        tok = llm.get_tokenizer()
        for k in sets:
            seqs = []
            for p in PROMPT_SETS[k]:  # one at a time: M=1, as scored
                ids = list(tok(p)["input_ids"])
                o = llm.generate([{"prompt_token_ids": ids}],
                                 SamplingParams(temperature=0, max_tokens=a.n))[0]
                seqs.append({"prompt": p, "start": len(ids),
                             "ids": ids + list(o.outputs[0].token_ids)})
            out = pathlib.Path(a.out) if a.out else pathlib.Path(a.out_dir) / f"set{k}.json"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(json.dumps({"set": k, "seqs_sha256": seqs_sha256(seqs), "seqs": seqs}))
            print(f"wrote {out}: set {k}, {len(seqs)} sequences")
    finally:
        _close(llm)


def cmd_score(a):
    if not (a.decode or a.prefill):
        raise SystemExit("pass --decode and/or --prefill")
    for kv in a.env or []:
        k, v = kv.split("=", 1)
        os.environ[k] = v
    if a.seqs_dir:
        seq_sets = load_seq_sets(a.seqs_dir)
    else:
        seq_sets = {}
        for f in a.seqs or []:
            doc = json.loads(pathlib.Path(f).read_text())
            seq_sets[int(doc.get("set", _set_id(pathlib.Path(f))))] = doc["seqs"]
    if not seq_sets:
        raise SystemExit("pass --seqs-dir or --seqs")
    extra = json.loads(a.llm_kwargs) if a.llm_kwargs else {}
    extra.update(scoring_llm_kwargs(a.max_num_seqs))
    if a.mode == "eager":
        extra["enforce_eager"] = True
    llm = _llm(a, **extra)
    try:
        results = {k: score_seqs(llm, seqs, a.decode, a.prefill,
                                 one_at_a_time=a.max_num_seqs == 1)
                   for k, seqs in sorted(seq_sets.items())}
    finally:
        _close(llm)
    for k, res in results.items():
        res.update({"set": k, "name": a.name, "mode": a.mode, "env": a.env or [],
                    "llm_kwargs": {x: v for x, v in extra.items() if x != "logits_processors"},
                    "max_num_seqs": a.max_num_seqs})
        out = pathlib.Path(a.out_dir) / f"set{k}" / f"{a.name}.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(res))
        msg = f"wrote {out}: {len(res['seqs'])} sequences"
        if a.decode:
            bad, n = top1_disagreements(res)
            msg += f", decode forced OK, raw top-1 != forced at {bad}/{n} steps"
        print(msg)


def cmd_greedy(a):
    """Free-running greedy on PROMPT_SETS[--set] (all prompts submitted at
    once, max_num_seqs as given), for T4b on either stack (Quinn, Nov 7:
    does the fork also diverge eager vs graph replay?)."""
    from vllm import SamplingParams

    extra = json.loads(a.llm_kwargs) if a.llm_kwargs else {}
    extra["max_num_seqs"] = a.max_num_seqs
    if a.mode == "eager":
        extra["enforce_eager"] = True
    llm = _llm(a, **extra)
    try:
        prompts = PROMPT_SETS[a.set]
        outs = llm.generate(prompts, SamplingParams(temperature=0, max_tokens=a.n))
        toks = [list(o.outputs[0].token_ids) for o in outs]
    finally:
        _close(llm)
    out = pathlib.Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"set": a.set, "mode": a.mode, "max_num_seqs": a.max_num_seqs,
                               "llm_kwargs": extra, "prompts": prompts, "tokens": toks}))
    print(f"wrote {out}: {len(toks)} prompts x {a.n} tokens")


def first_divergence(x: list[int], y: list[int]) -> int | None:
    return next((i for i, (p, q) in enumerate(zip(x, y)) if p != q),
                None if len(x) == len(y) else min(len(x), len(y)))


def cmd_compare_greedy(a):
    ga, gb = (json.loads(pathlib.Path(f).read_text()) for f in (a.a, a.b))
    same = 0
    for i, (x, y) in enumerate(zip(ga["tokens"], gb["tokens"])):
        d = first_divergence(x, y)
        same += d is None
        print(f"prompt {i}: " + ("identical" if d is None else f"differs at {d}"))
    print(f"identical {same}/{len(ga['tokens'])}")


def cmd_seqs_from_golden(a):
    """Golden greedy records (T5's FLINT_SM70_GOLDEN) -> a scorable seqs
    file, for forced decode of the golden continuation (T5 near-tie rule)."""
    seqs = golden_seqs(json.loads(pathlib.Path(a.golden).read_text()), a.match)
    if not seqs:
        raise SystemExit(f"no golden prompt contains {a.match!r}")
    out = pathlib.Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"set": a.set, "seqs_sha256": seqs_sha256(seqs), "seqs": seqs}))
    print(f"wrote {out}: {len(seqs)} golden sequence(s) as set {a.set}")


def cmd_compare(a):
    s = stats(metric(json.load(open(a.a)), a.metric), metric(json.load(open(a.b)), a.metric))
    print(json.dumps(s))
    if a.out:
        json.dump(s, open(a.out, "w"))


def cmd_envelope(a):
    env = build_envelope(a.scores_dir, a.min_sets, a.pairs)
    pathlib.Path(a.out).write_text(json.dumps(env, indent=1))
    for pair in OPTIONAL_PAIRS:
        if not a.pairs and pair not in env["pairs"]:
            print(f"{pair}: skipped, no setK/{PAIRS[pair][1]}.json in {a.scores_dir} "
                  f"(its gate fails until they are scored)")
    for pair, by_metric in env["pairs"].items():
        for m, e in by_metric.items():
            for k, s in e["per_set"].items():
                print(f"{pair} {m} set{k}: mean={s['mean']:.4g} max={s['max']:.4g} "
                      f">{OVER}={s['over_0_1']}/{s['n']} >{OVER_1_0}={s['over_1_0']}")
            an = e["anchor"]
            print(f"{pair} {m} ANCHOR: mean={an['mean']:.4g} max={an['max']:.4g} "
                  f">{OVER}<={an['over_0_1']} >{OVER_1_0}<={an['over_1_0']}")
        if by_metric:
            ea = effective_anchor(env, pair, next(iter(by_metric)))
            print(f"{pair} GATE: max over {'+'.join(ea['max_over'])} = {ea['max']:.4g}, "
                  f">{OVER_1_0} anchor {ea['over_1_0']} -> "
                  f"{limits_text(ea).split(', ', 1)[1]}")
    print(f"-> {a.out}")


