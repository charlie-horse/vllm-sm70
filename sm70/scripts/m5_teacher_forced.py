#!/usr/bin/env python3
"""Teacher-forced logprob comparison for Flint (M5 T4a/T4c/T4d/T7), runnable
on either stack: this repo's vllm-sm70 build or the fork (cf9492a). It
imports only vllm, torch and the stdlib (never vllm_sm70), so it calibrates
the fork's own envelope with the same code that gates ours.

Why teacher forcing: Flint's greedy output flips on last-bit differences
(MoE top-6/256 routing), so free-running token equality between two valid
numerical paths is not a correctness signal. Scoring FIXED token sequences
gives each path identical inputs at every position; the per-token |dlogprob|
is then the path's own numeric difference, with no cascade.

Two metrics per scored token (continuation positions start..end):
  decode   forced decode. The prompt is prefilled, then every continuation
           token is generated by a real decode step (eager or CUDA-graph
           replay), with ForceRefLogitsProcessor masking the logits to the
           reference token. logprobs_mode="raw_logprobs" returns the model's
           logprob from BEFORE the processor (vllm/v1/sample/sampler.py,
           Sampler.forward: raw logprobs are computed before
           apply_logits_processors), so the forced token's logprob and the
           raw top-1 are the model's own. Step 0 comes from the prompt's
           prefill pass; steps 1.. are decode steps.
  prefill  prompt_logprobs over the whole sequence in one prefill pass (the
           old T4a metric). It never exercises decode or graph replay.

Subcommands (each LLM build runs in this process; TP workers spawn, so all
work happens under the __main__ guard):
  gen      --model M --set K [--set K ...] --out-dir D [--n 64]
           eager greedy continuations of prompt set K -> D/setK.json
  score    --model M (--seqs-dir D | --seqs F ...) --out-dir O --name N
           --mode eager|graphs [--decode] [--prefill] [--max-num-seqs 1]
           [--env K=V ...] [--llm-kwargs JSON] [--hf-overrides JSON]
           -> O/setK/N.json (per sequence: decode and/or prefill logprobs)
  compare  A.json B.json [--metric decode|prefill]
           n/mean/max/count>0.1/count>1.0
  envelope --scores-dir O --out env.json [--pairs P ...]   per pair and
           metric: mean, max, count>0.1, count>1.0 per set, anchor = max
           over sets
  greedy, compare-greedy, seqs-from-golden: free-run evidence (T4b, T5)

Envelope layout (fork calibration): O/setK/{eager,eager2,graphs,unfused}.json,
all scored with --decode --prefill, EACH FROM ITS OWN ENGINE INSTANCE (one
`score` run = one LLM build = one name), plus the optional
O/setK/graphsonly.json (mode NONE + FULL CUDA graphs, see T4e). Pairs:
eager_vs_graphs = eager vs graphs, fused_vs_unfused = eager vs unfused
(unfused = eager with VLLM_SM70_FLINT_QK_ROPE_KV=0), eager_vs_eager = eager vs
eager2 (a second, separate eager instance: the stack's engine-instance
nondeterminism), eager_vs_graphsonly = eager vs graphsonly (only when the
graphsonly files exist).

Gate (Quinn, Nov 7), per (pair, set, metric), via effective_anchor():
ours mean <= GATE_MEAN_FACTOR x that metric's anchor mean; ours max <=
GATE_MAX_FACTOR x the pair's anchor max over BOTH metrics (decode and
prefill); ours count > OVER_1_0 nats <= max(1, ceil(GATE_COUNT_FACTOR x the
pair's anchor count over both metrics)). An envelope without the over_1_0
counts (built before Nov 7) fails closed: rebuild it with `envelope`.

Common LLM args match the M5 tests: TP2, fp16, max_model_len 8192,
gpu_memory_utilization 0.85, prefix caching off, max_num_seqs 1 (M=1 at every
decode step, in eager and in graph replay). Pass --hf-overrides for this
repo's FlintSm70ForCausalLM; omit it on the fork (its FlintForCausalLM is the
default architecture).
"""
