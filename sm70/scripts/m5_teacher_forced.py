# Forced decoding
# --------------------------------------------------------------------------
class ForceRefLogitsProcessor(LogitsProcessor):
    """V1 batch-level logits processor that forces a fixed continuation.

    A request opts in with ``SamplingParams(extra_args={"m5_force": ids})``.
    At each sampling step the request's step index is the length of its
    running output-token list (the list vLLM hands over in
    BatchUpdate.added; with async scheduling the runner replaces the -1
    placeholders before the processors run). Its logits row is set to -inf
    except the reference token for that step (set to 0), so greedy sampling
    picks exactly the reference. The processor is not argmax-invariant, so
    the sampler applies it for greedy requests too (after the raw logprobs
    were taken). Rows without the key, or past the end of their reference,
    are left untouched.
    """

    @classmethod
    def validate_params(cls, sampling_params):
        ref = (sampling_params.extra_args or {}).get(FORCE_KEY)
        if ref is None:
            return
        if not isinstance(ref, (list, tuple)) or not ref or not all(
            isinstance(t, int) and not isinstance(t, bool) and t >= 0 for t in ref
        ):
            raise ValueError(f"extra_args[{FORCE_KEY!r}] must be a non-empty list of token ids")
        if sampling_params.max_tokens is not None and sampling_params.max_tokens > len(ref):
            raise ValueError(
                f"max_tokens {sampling_params.max_tokens} > forced reference length {len(ref)}"
            )

    def __init__(self, vllm_config, device, is_pin_memory):
        self.device = device
        # batch index -> (reference ids, live output-token list)
        self.forced: dict[int, tuple[list[int], list[int]]] = {}

    def is_argmax_invariant(self) -> bool:
        return False

    @staticmethod
    def _new_state(params, prompt_tok_ids, output_tok_ids):
        extra = getattr(params, "extra_args", None) or {}
        ref = extra.get(FORCE_KEY)
        return None if ref is None else (list(ref), output_tok_ids)

    def update_state(self, batch_update) -> None:
        process_dict_updates(self.forced, batch_update, self._new_state)

    def targets(self) -> tuple[list[int], list[int]]:
        """(rows, tokens) to force at this step."""
        rows, toks = [], []
        for row, (ref, out) in sorted(self.forced.items()):
            step = len(out)
            if step < len(ref):
                rows.append(row)
                toks.append(ref[step])
        return rows, toks

    def apply(self, logits):
        if not self.forced:
            return logits
        rows, toks = self.targets()
        if not rows:
            return logits
        r = torch.tensor(rows, dtype=torch.long).to(logits.device)
        t = torch.tensor(toks, dtype=torch.long).to(logits.device)
        logits[r] = float("-inf")
        logits[r, t] = 0.0
        return logits


def ensure_importable() -> None:
    """Make FORCE_FQCN importable here and in every spawned/forked process."""
    d = str(SCRIPTS_DIR)
    if d not in sys.path:
        sys.path.insert(0, d)
    pp = os.environ.get("PYTHONPATH", "")
    if d not in pp.split(os.pathsep):
        os.environ["PYTHONPATH"] = d + (os.pathsep + pp if pp else "")


def scoring_llm_kwargs(max_num_seqs: int = 1) -> dict:
    """LLM(...) kwargs every scoring run uses, on both stacks."""
    ensure_importable()
    return {
        "logits_processors": [FORCE_FQCN],
        "logprobs_mode": "raw_logprobs",
        "enable_prefix_caching": False,
        "max_num_seqs": max_num_seqs,
    }


def seqs_sha256(seqs: list[dict]) -> str:
    blob = json.dumps([[s["start"], s["ids"]] for s in seqs], separators=(",", ":"))
    return hashlib.sha256(blob.encode()).hexdigest()


def _decode_params(seq: dict):
    from vllm import SamplingParams

    ref = list(seq["ids"][seq["start"]:])
    return SamplingParams(
        temperature=0, max_tokens=len(ref), logprobs=1, ignore_eos=True,
        extra_args={FORCE_KEY: ref},
    )


def decode_record(seq: dict, out) -> dict:
    """Forced-decode result of one sequence; raises ForcingError if the
    generated ids are not the reference."""
    c = out.outputs[0]
    ref = list(seq["ids"][seq["start"]:])
    got = list(c.token_ids)
    if got != ref:
        pos = next((i for i, (a, b) in enumerate(zip(got, ref)) if a != b), min(len(got), len(ref)))
        raise ForcingError(
            f"forcing failed for {seq.get('prompt', '')[:40]!r}: generated {len(got)} tokens, "
            f"reference {len(ref)}, first difference at {pos}"
        )
    if c.logprobs is None or len(c.logprobs) != len(ref):
        raise ForcingError("no per-step logprobs returned (logprobs=1 required)")
    lp, top1, top1_lp = [], [], []
    for tok, step in zip(ref, c.logprobs):
        lp.append(float(step[tok].logprob))
        best_tok, best = min(step.items(), key=lambda kv: (kv[1].rank, kv[0]))
        top1.append(int(best_tok))
        top1_lp.append(float(best.logprob))
    return {"decode": lp, "decode_top1": top1, "decode_top1_logprob": top1_lp}


def forced_decode(llm, seqs: list[dict], one_at_a_time: bool = True) -> list[dict]:
    """Forced-decode every sequence. one_at_a_time: one generate() per
    sequence, so M=1 at every step regardless of max_num_seqs."""
    prompts = [{"prompt_token_ids": list(s["ids"][: s["start"]])} for s in seqs]
    if one_at_a_time:
        outs = [llm.generate([p], _decode_params(s))[0] for p, s in zip(prompts, seqs)]
    else:
        outs = llm.generate(prompts, [_decode_params(s) for s in seqs])
    return [decode_record(s, o) for s, o in zip(seqs, outs)]


def prefill_scores(llm, seqs: list[dict]) -> list[list[float]]:
    from vllm import SamplingParams

    outs = llm.generate(
        [{"prompt_token_ids": s["ids"]} for s in seqs],
        SamplingParams(max_tokens=1, prompt_logprobs=1),
    )
    return [
        [float(o.prompt_logprobs[i][s["ids"][i]].logprob) for i in range(s["start"], len(s["ids"]))]
        for s, o in zip(seqs, outs)
    ]


def score_seqs(llm, seqs: list[dict], decode=True, prefill=True, one_at_a_time=True) -> dict:
    """Score one prompt set with an already built LLM."""
    recs = [dict() for _ in seqs]
    if decode:
        for r, d in zip(recs, forced_decode(llm, seqs, one_at_a_time)):
            r.update(d)
    if prefill:
        for r, p in zip(recs, prefill_scores(llm, seqs)):
            r["prefill"] = p
    return {"seqs_sha256": seqs_sha256(seqs), "seqs": recs}


def metric(score: dict, name: str) -> list[list[float]]:
    try:
        return [r[name] for r in score["seqs"]]
    except KeyError:
        raise KeyError(f"score file has no {name!r} metric (score with --{name})") from None


def top1_disagreements(score: dict) -> tuple[int, int]:
    """(steps whose raw top-1 is not the forced token, steps)."""
    n = bad = 0
    for r in score["seqs"]:
        ref_lp = r.get("decode") or []
        for lp, t1lp in zip(ref_lp, r.get("decode_top1_logprob") or []):
            n += 1
            bad += t1lp > lp
    return bad, n


